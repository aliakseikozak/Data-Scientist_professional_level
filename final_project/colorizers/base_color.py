"""
БАЗОВЫЙ КЛАСС ДЛЯ МОДЕЛЕЙ РАСКРАШИВАНИЯ
========================================
Содержит общую логику для работы с LAB цветовым пространством:
- Нормализация/денормализация L и AB каналов
- Базовые преобразования цветов

L-канал: яркость (Lightness) [0-100]
AB-каналы: цветность (Chroma) [-110, 110]

Все модели наследуются от этого класса
"""

import torch
from torch import nn

class BaseColor(nn.Module):
    def __init__(self):
        """
        Инициализация параметров нормализации для LAB цветового пространства
        """
        super(BaseColor, self).__init__()
        
        # Среднее и нормализация для L-канала (яркость)
        self.l_cent = 50.0      # Центрирование вокруг 50
        self.l_norm = 100.0     # Нормализация к диапазону [-0.5, 0.5]
        
        # Нормализация для ab-каналов (цветность)
        self.ab_norm = 110.0    # Приведение к диапазону [-1, 1]

    # ---------- НОРМАЛИЗАЦИЯ L-КАНАЛА ----------
    def normalize_l(self, in_l):
        """
        Нормализация L-канала для нейросети
        Преобразует [0, 100] → [-0.5, 0.5]
        """
        return (in_l - self.l_cent) / self.l_norm

    def unnormalize_l(self, in_l):
        """
        Денормализация L-канала
        Преобразует [-0.5, 0.5] → [0, 100]
        """
        return in_l * self.l_norm + self.l_cent

    # ---------- НОРМАЛИЗАЦИЯ AB-КАНАЛОВ ----------
    def normalize_ab(self, in_ab):
        """
        Нормализация ab-каналов для нейросети
        Преобразует [-110, 110] → [-1, 1]
        """
        return in_ab / self.ab_norm

    def unnormalize_ab(self, in_ab):
        """
        Денормализация ab-каналов
        Преобразует [-1, 1] → [-110, 110]
        """
        return in_ab * self.ab_norm